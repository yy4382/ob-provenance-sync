import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "node:module";
import { readFileSync } from "node:fs";
import { gzipSync } from "node:zlib";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

// The agent CLI ships inside the plugin, gzipped, so BRAT installs it too.
const agentCli = {
  name: "agent-cli",
  setup(build) {
    build.onResolve({ filter: /^virtual:agent-cli$/ }, () => ({ path: "agent-cli", namespace: "agent-cli" }));
    build.onLoad({ filter: /.*/, namespace: "agent-cli" }, () => {
      const cli = new URL("../cli/dist/cli.js", import.meta.url);
      return { contents: `export default ${JSON.stringify(gzipSync(readFileSync(cli)).toString("base64"))};`, loader: "js" };
    });
  },
};

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ["src/main.ts"],
  plugins: [agentCli],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtinModules,
    "node:*",
  ],
  format: "cjs",
  target: "es2021",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: prod,
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
